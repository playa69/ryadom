/**
 * Writes stars.css: one seeded SVG tile of scattered stars, used as the top layer of the
 * atmosphere background. A single large random tile (instead of a small repeating dot pattern)
 * keeps the sky from showing an obvious grid. Run: node packages/design/gen-stars.mjs
 */
import { writeFileSync } from 'node:fs'

const W = 1600
const H = 1200
const COUNT = 96

function mulberry32(seed) {
  return () => {
    seed |= 0
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const rand = mulberry32(20261001)
const tints = ['255,255,255', '255,255,255', '255,255,255', '190,225,255', '160,235,225', '200,180,255']
const shapes = []

for (let i = 0; i < COUNT; i++) {
  const x = (rand() * W).toFixed(0)
  const y = (rand() * H).toFixed(0)
  const roll = rand()
  const tint = tints[Math.floor(rand() * tints.length)]
  if (roll < 0.7) {
    shapes.push(`<circle cx='${x}' cy='${y}' r='${(0.6 + rand() * 0.4).toFixed(2)}' fill='rgba(${tint},${(0.35 + rand() * 0.3).toFixed(2)})'/>`)
  } else if (roll < 0.94) {
    shapes.push(`<circle cx='${x}' cy='${y}' r='${(1 + rand() * 0.4).toFixed(2)}' fill='rgba(${tint},${(0.55 + rand() * 0.25).toFixed(2)})'/>`)
  } else {
    // A rare brighter star with a soft halo, so the sky is not a flat field of identical dots.
    shapes.push(`<circle cx='${x}' cy='${y}' r='5' fill='rgba(${tint},0.10)'/><circle cx='${x}' cy='${y}' r='1.7' fill='rgba(${tint},0.9)'/>`)
  }
}

const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='${W}' height='${H}' viewBox='0 0 ${W} ${H}'>${shapes.join('')}</svg>`
const css = `/* Generated by gen-stars.mjs — do not edit by hand. */
:root {
  --ryadom-stars: url("data:image/svg+xml,${svg.replace(/#/g, '%23').replace(/"/g, "'")}");
}
`
writeFileSync(new URL('./stars.css', import.meta.url), css)
console.log(`stars.css: ${css.length} bytes`)
