"""Маскирование персональных данных перед внешними моделями (PROTEUS-242, задача 2.1).

Применяется к тексту человека до вызова модели извлечения заметок, до записи документа в Cognee и до модели итога.
Маска — слово в квадратных скобках: модель видит, что здесь был, например, телефон, но не сам номер. Функция чистая и
без побочных эффектов; ни текст, ни найденное в журнал не пишутся.
"""

import re

# Порядок важен: сначала то, что содержит цифры и «@», потом общие длинные числа.
_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("[почта]", re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+", re.UNICODE)),
    ("[ссылка]", re.compile(r"(?:https?://|www\.)\S+|\b[\w-]+\.(?:ru|com|org|net|рф|io|me|su)(?:/\S*)?\b", re.IGNORECASE)),
    ("[ник]", re.compile(r"(?<![\w@])@[A-Za-z0-9_]{3,32}\b")),
    # Телефон: +7 (999) 123-45-67, 8 999 123 45 67, 89991234567, 999-123-45-67
    ("[телефон]", re.compile(r"(?<![\w])(?:\+7|8|7)?[\s(.-]*\d{3}[\s).-]*\d{3}[\s.-]*\d{2}[\s.-]*\d{2}(?!\d)")),
    # Карта: 4 группы по 4 цифры (с пробелами или дефисами) или 16 подряд
    ("[карта]", re.compile(r"(?<!\d)(?:\d{4}[\s-]?){3}\d{4}(?!\d)")),
    # Паспорт: «паспорт 4510 123456», серия и номер
    ("[документ]", re.compile(r"(?:паспорт|снилс|инн|полис|водительск\w+)\D{0,12}[\d\s-]{6,}", re.IGNORECASE)),
    # Адрес: «ул. Ленина, д. 5, кв. 12», «улица Мира 3»
    (
        "[адрес]",
        re.compile(
            r"\b(?:ул\.?|улица|пр\.?|проспект|пер\.?|переулок|бульвар|б-р|пл\.?|площадь|ш\.?|шоссе)\s+"
            r"[А-ЯЁA-Z][\w\-ёЁ]*(?:\s+[А-ЯЁA-Z][\w\-ёЁ]*)?(?:[,\s]+(?:д\.?|дом)\s*\d+[\w/]*)?(?:[,\s]+(?:кв\.?|квартира)\s*\d+)?",
            re.UNICODE,
        ),
    ),
    # Длинные числа (счета, идентификаторы): 9 цифр и больше
    ("[число]", re.compile(r"(?<!\d)\d{9,}(?!\d)")),
)


def mask(text: str) -> str:
    """Текст с замаскированными персональными данными."""
    masked = text
    for label, pattern in _PATTERNS:
        masked = pattern.sub(label, masked)
    return masked


def has_personal_data(text: str) -> bool:
    """В тексте есть что маскировать."""
    return mask(text) != text
