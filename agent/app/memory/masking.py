"""Маскирование персональных данных перед вызовом модели извлечения (MEM-7.3).

Телефоны, email, ссылки и @ники, номера карт, паспорта, СНИЛС, ИНН, длинные числа и адреса заменяются плейсхолдерами: модели
они не нужны, а запоминать их всё равно запрещено (класс `contact_pii`). Имена на входе не маскируются (имя близкого нужно
для `person`); фамилии отсекаются на выходе фильтром `third_party_pii`. Функция идемпотентна: плейсхолдеры повторно не
находятся. NER (natasha) по умолчанию не подключается (MEM-7.3).
"""

import re

_FLAGS = re.IGNORECASE

# Порядок важен: сначала то, что содержит другие шаблоны (email содержит @ник, карта — длинное число).
_RULES: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"https?://\S+|www\.\S+", _FLAGS), "[ссылка]"),
    (re.compile(r"[\w.+\-]+@[\w\-]+\.[\w.\-]+", _FLAGS), "[email]"),
    (re.compile(r"(?<![\w@\[])[a-z0-9\-]+\.(?:ru|com|рф|org|net|io|me|su|info|рус)\b\S*", _FLAGS), "[ссылка]"),
    (re.compile(r"(?<![\w\[])@[a-z0-9_.]{2,}", _FLAGS), "[ник]"),
    (re.compile(r"(?<![a-z])[a-z]{2}\d{2}(?:\s?[a-z0-9]{4}){3,7}(?:\s?[a-z0-9]{1,4})?(?![a-z0-9])", _FLAGS), "[счёт]"),
    (
        re.compile(r"паспорт\w*[\s:№#]*(?:серии?\s*)?\d{2}\s?\d{2}(?:\s*(?:номер|№|#)?\s*\d{6})?", _FLAGS),
        "[документ]",
    ),
    (re.compile(r"(?<!\d)\d{3}-\d{3}-\d{3}[\s\-]\d{2}(?!\d)"), "[документ]"),  # СНИЛС
    (re.compile(r"\bинн\b[\s:№#]*\d{10,12}", _FLAGS), "[документ]"),
    (re.compile(r"(?<!\d)(?:\d[ \-]?){12,18}\d(?!\d)"), "[карта]"),  # 13–19 цифр, в том числе группами
    (
        re.compile(r"(?:\+\s*7|(?<!\d)8)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)"),
        "[телефон]",
    ),
    (re.compile(r"(?<!\d)\d(?:[\s\-()]*\d){6,}(?!\d)"), "[число]"),  # 7 и больше цифр подряд, в том числе с разделителями
    (re.compile(r"(?<!\d)\d{5,}(?!\d)"), "[число]"),
    (
        re.compile(
            r"(?<![\w\[])(?:ул\.|улиц[аеуы]|проспект\w*|пр-т|переул\w*|бульвар\w*|шоссе|наб\.)\s*[\w\-]+(?:\s[\w\-]+)?",
            _FLAGS,
        ),
        "[адрес]",
    ),
    (re.compile(r"(?<![\w\[])(?:д\.|дом|кв\.|квартир[аеуы]|корп\.|корпус|стр\.)\s*\d+\w*", _FLAGS), "[адрес]"),
)


def mask(text: str) -> str:
    """Текст с плейсхолдерами вместо контактов, документов, длинных чисел и адресов."""
    for pattern, placeholder in _RULES:
        text = pattern.sub(placeholder, text)
    return text
