"""Ответы агента: модель пишет их по истории диалога, шаблоны — запасной вариант.

Шаблоны идут по кругу, когда модель не ответила (или `LLM_MODE=template`): человек не остаётся без ответа.
Кризис определяется по списку слов и отвечает фиксированным текстом, модель в этот путь не входит.
"""

import re
from collections.abc import Sequence

from app.services.dialog_store import Message

REPLIES = (
    "Я здесь. Расскажи, что случилось.",
    "Звучит тяжело. Что из этого задело сильнее всего?",
    "Похоже на усталость и обиду одновременно. Так?",
    "Спасибо, что говоришь об этом. Что бы тебе сейчас помогло?",
    "Давай помедленнее. Что происходило прямо перед этим?",
)

CRISIS_WORDS = ("не хочу жить", "покончить", "убить себя", "умереть", "нет смысла жить")

# Кризисное вмешательство детерминировано: никаких генеративных фраз (specs/agent-core «Кризисный протокол»).
CRISIS_SAFETY_TEXT = "Если тебе сейчас опасно, позвони по одному из номеров ниже."
CRISIS_REPLY = "Я слышу, что тебе очень тяжело. Ты не один на один с этим. Давай посмотрим, кому можно позвонить прямо сейчас."

# Ответ звучит голосом, поэтому коротко и без разметки: списки, markdown и эмодзи озвучка прочла бы вслух.
SYSTEM_PROMPT = (
    "Ты — «Рядом», тёплый и спокойный собеседник в приложении эмоциональной поддержки «Слышу Рядом». "
    "Говоришь по-русски, на «ты», простыми словами.\n"
    "Правила:\n"
    "- Отвечай коротко: одно-три предложения. Твой ответ будет озвучен голосом.\n"
    "- Никаких списков, markdown, эмодзи и заголовков, только обычная речь.\n"
    "- Сначала признай чувство человека, потом, если уместно, задай один мягкий вопрос. Не задавай два вопроса сразу.\n"
    "- Не давай советов в лоб, не оценивай, не спорь, не поучай. Не ставь диагнозов и не назначай лекарства: ты не врач.\n"
    "- Если человек говорит о желании навредить себе или о том, что жить не хочется, скажи, что ему важно сейчас "
    "быть не одному, и мягко предложи позвонить близкому человеку или на линию помощи.\n"
    "- Не выдумывай факты о человеке, опирайся только на то, что он сказал.\n"
    "- Если человек пишет не по-русски, ответь на его языке так же коротко."
)


def is_crisis(text: str) -> bool:
    lower = text.lower()
    return any(word in lower for word in CRISIS_WORDS)


def next_reply(index: int) -> str:
    return REPLIES[index % len(REPLIES)]


def chat_messages(history: Sequence[Message], limit: int) -> list[dict[str, str]]:
    """Что видит модель: системный промпт и последние `limit` сообщений диалога, начиная с реплики человека."""
    recent = list(history[-limit:])
    while recent and recent[0].role != "user":
        recent.pop(0)
    return [{"role": "system", "content": SYSTEM_PROMPT}, *({"role": m.role, "content": m.text} for m in recent)]


def split_sentences(text: str) -> list[str]:
    """Предложения для озвучки: первое звучит, пока остальные ещё синтезируются."""
    return [part.strip() for part in re.findall(r"[^.!?…]+[.!?…]*", text) if part.strip()]
